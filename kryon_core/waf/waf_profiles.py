def normalize_waf(waf: str) -> str:
    value = (waf or "").strip().lower().replace("-", " ")
    underscored = value.replace(" ", "_")
    spaced = underscored.replace("_", " ")
    if spaced in WAF_ALIASES:
        return WAF_ALIASES[spaced]
    if underscored in WAF_ALIASES:
        return WAF_ALIASES[underscored]
    if underscored in WAF_SIGNATURES:
        return underscored
    for alias, canonical in WAF_ALIASES.items():
        if alias in spaced or alias in underscored:
            return canonical
    for canonical in WAF_SIGNATURES:
        needle = canonical.replace("_", " ")
        if needle in spaced or canonical in underscored:
            return canonical
    return underscored


def waf_pref_bonus(operators, waf) -> int:
    if not waf:
        return 0
    preferred = set(WAF_EVASION_OPS.get(normalize_waf(waf), []))
    return sum(1 for operator in operators if operator in preferred)


def known_waf_vendor(name: str) -> bool:
    vendor = normalize_waf(name)
    return vendor in WAF_SIGNATURES


def fingerprint_channels(headers: str = "", cookies: str = "", body: str = "", status_code: int = 0):
    header_blob = (headers or "").lower()
    cookie_blob = (cookies or "").lower()
    body_blob = (body or "").lower()
    best, best_score, best_matched = "unknown", 0, []
    for vendor, signature in WAF_SIGNATURES.items():
        matched = []
        score = 0
        for pattern, weight in signature.get("headers", []):
            if pattern in header_blob:
                matched.append(pattern)
                score += weight
        for pattern, weight in signature.get("cookies", []):
            if pattern in cookie_blob or pattern in header_blob:
                matched.append(pattern)
                score += weight
        for pattern, weight in signature.get("body", []):
            if pattern in body_blob:
                matched.append(pattern)
                score += weight
        min_score = signature.get("min_score", 1)
        if score >= min_score and score > best_score:
            best, best_score, best_matched = vendor, score, matched
    return best, best_score, best_matched


def fingerprint(blob: str = "", headers: str = "", cookies: str = "", body: str = "",
                status_code: int = 0):
    """Blob form (legacy) searches all channels; prefer fingerprint_channels."""
    if headers or cookies or body or status_code:
        return fingerprint_channels(headers, cookies, body, status_code)
    text = blob or ""
    return fingerprint_channels(text, text, text, 0)


def ip_is_cdn(ip: str) -> bool:
    try:
        addr = ipaddress.ip_address((ip or "").strip())
    except ValueError:
        return False
    return any(addr in network for network in CDN_NETWORKS)


def classify_http(status_code: int = 0, headers: str = "", body: str = "", cookies: str = ""):
    header_blob = (headers or "").lower()
    body_blob = (body or "").lower()
    vendor, _, _ = fingerprint_channels(headers, cookies, body, status_code)
    combined = header_blob + "\n" + body_blob
    rate = status_code == 429 or any(marker in combined for marker in RATE_MARKERS)
    captcha = any(marker in combined for marker in CAPTCHA_MARKERS)
    challenge = any(marker in combined for marker in JS_CHALLENGE_MARKERS)
    block_kw = any(marker in body_blob for marker in BLOCK_BODY_MARKERS)
    err_kw = any(marker in body_blob for marker in APP_ERROR_MARKERS)
    if rate:
        cls, action = "rate_limit", (
            "Payload YAKMA. throttle + jitter (adaptive_evasion_step); "
            "gerekirse UA/IP rotasyonu (yetkili scope)."
        )
    elif captcha:
        cls, action = "captcha", (
            "CAPTCHA — payload yakma. discover_origin veya soğuma; evolve_payload atlama."
        )
    elif challenge:
        cls, action = "js_challenge", (
            "JS challenge — payload yakma. Origin keşfi veya tarayıcı/soğuma; "
            "evolve_payload atlama."
        )
    elif status_code in (403, 406, 503, 501) and (vendor != "unknown" or block_kw):
        cls, action = "waf_block", (
            f"WAF blok ({vendor}). fingerprint_waf → evolve_payload(waf), "
            "CDN ise discover_origin."
        )
    elif err_kw or status_code in (500, 502):
        cls, action = "app_error", (
            "Backend hatası — muhtemelen WAF'ı GEÇTİN. Hata mesajını "
            "SQLi/SSTI sinyali için analiz et."
        )
    elif status_code in (200, 201, 301, 302):
        cls, action = "origin_reached", "Bloklanmadı — payload geçmiş olabilir, sonucu doğrula."
    else:
        cls, action = "unknown", "Sınıflandırılamadı — daha fazla sinyal topla."
    return {
        "classification": cls,
        "status_code": status_code,
        "waf_vendor_hint": vendor if vendor != "unknown" else None,
        "recommended_action": action,
    }
