def _get_attr(obj: Any, key: str, default: Any = None) -> Any:
    if isinstance(obj, Mapping):
        return obj.get(key, default)
    return getattr(obj, key, default)


def _scrub_text(
    text: Any,
    secret_values: Sequence[str] = (),
    *,
    single_line: bool = True,
) -> str:
    """Scrub secret values and generic credential/token literals from text."""
    raw = str(text or "")
    if not raw:
        return ""
    cleaned = redact_secrets(raw, secret_values)
    cleaned = _RAW_JWT_RE.sub("<REDACTED_JWT>", cleaned)
    cleaned = _BEARER_HEADER_RE.sub("Bearer <REDACTED_TOKEN>", cleaned)
    cleaned = _COOKIE_HEADER_RE.sub(lambda m: f"{m.group(1)}: <REDACTED_COOKIE>", cleaned)
    cleaned = _COOKIE_KV_RE.sub(lambda m: f"{m.group(1)}=<REDACTED_COOKIE>", cleaned)
    cleaned = _AWS_KEY_RE.sub("<REDACTED_KEY>", cleaned)
    cleaned = _PEM_KEY_RE.sub("<REDACTED_PRIVATE_KEY>", cleaned)
    cleaned = _CREDENTIAL_LITERAL_RE.sub(lambda m: f"{m.group(1)}<REDACTED_SECRET>", cleaned)
    if single_line:
        return " ".join(cleaned.split())
    lines = [" ".join(ln.split()) for ln in cleaned.splitlines()]
    return "\n".join(ln for ln in lines if ln)


def _strip_method_prefix(raw_op: str) -> str:
    text = str(raw_op or "").strip()
    parts = text.split(None, 1)
    if len(parts) == 2 and parts[0].upper() in {"GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"}:
        return parts[1].strip()
    return text


def _normalize_route_template(url_or_path: str) -> str:
    """Normalize a URL or path into a lightweight `{id}` route template."""
    raw = _strip_method_prefix(url_or_path)
    if not raw:
        return "/"
    path = (urlsplit(raw).path or "/").strip()
    if len(path) > 1:
        path = path.rstrip("/")
    if not path or path == "/":
        return "/"
    segs: list[str] = []
    for seg in path.split("/"):
        if not seg:
            continue
        low = seg.lower()
        if (
            low.isdigit()
            or _UUID_SEG_RE.fullmatch(low)
            or _HEX_ID_SEG_RE.fullmatch(low)
            or _PREFIXED_ID_SEG_RE.fullmatch(low)
            or _TEMPLATE_SEG_RE.fullmatch(low)
        ):
            segs.append("{id}")
        else:
            segs.append(low)
    return "/" + "/".join(segs)


def _extract_family_and_subfamily(url_or_path: str) -> tuple[str, str | None]:
    """Extract normalized resource family and optional API sub-family from a path/URL."""
    raw = _strip_method_prefix(url_or_path)
    path = (urlsplit(raw).path or "/").strip()
    segs = [seg for seg in path.split("/") if seg]
    while segs and (
        _PREFIX_SEGMENT_RE.fullmatch(segs[0])
        or not any(ch.isalnum() for ch in segs[0])
    ):
        segs.pop(0)
    if not segs:
        return "root", None
    first = segs[0]
    if (first.startswith("{") and first.endswith("}")) or first.startswith("$") or "=" in first:
        return "root", None
    if len(segs) == 1 and "." in first:
        return "root", None
    fam = first.lower()
    sub: str | None = None
    if len(segs) >= 2:
        cand = segs[1]
        if (
            not cand.isdigit()
            and not _UUID_SEG_RE.fullmatch(cand)
            and not _HEX_ID_SEG_RE.fullmatch(cand)
            and not _TEMPLATE_SEG_RE.fullmatch(cand)
            and any(ch.isalnum() for ch in cand)
            and "=" not in cand
            and not (len(segs) == 2 and "." in cand)
        ):
            sub = cand.lower()
    return fam, sub


def _cluster_route_and_family_sets(
    cluster: Any,
) -> tuple[set[str], set[str], list[str], list[str], list[str]]:
    raw_families = _get_attr(cluster, "families", None) or ()
    families = [str(f).strip() for f in raw_families if str(f).strip()]
    family_set = {f.lower() for f in families}
    routes = [str(r).strip() for r in (_get_attr(cluster, "routes", None) or ()) if str(r).strip()]
    writes = [str(w).strip() for w in (_get_attr(cluster, "write_ops", None) or ()) if str(w).strip()]
    route_set = {_normalize_route_template(r) for r in routes}
    route_set.update(_normalize_route_template(w) for w in writes)
    return route_set, family_set, families, routes, writes


def _path_matches_cluster(
    raw_path: str,
    *,
    route_set: set[str],
    family_set: set[str],
) -> bool:
    if not raw_path:
        return False
    if "*" in family_set or "all" in family_set:
        return True
    tmpl = _normalize_route_template(raw_path)
    if tmpl in route_set:
        return True
    fam, sub = _extract_family_and_subfamily(raw_path)
    if fam in family_set or (sub is not None and sub in family_set):
        return True
    if not family_set and route_set:
        implicit_fams = {_extract_family_and_subfamily(r)[0] for r in route_set} - {"root"}
        if fam in implicit_fams or (sub is not None and sub in implicit_fams):
            return True
    return False


def _lead_matches_shard(
    lead: Mapping[str, Any],
    *,
    shard_id: str,
    route_set: set[str],
    family_set: set[str],
) -> bool:
    lead_src = str(lead.get("source_shard") or "").strip()
    if lead_src:
        if lead_src == shard_id:
            return True
        if lead_src.lower() != "bootstrap":
            return False

    explicit_fams = lead.get("families")
    if isinstance(explicit_fams, Sequence) and not isinstance(explicit_fams, (str, bytes)):
        if {str(f).strip().lower() for f in explicit_fams if str(f).strip()} & family_set:
            return True
    explicit_fam = str(lead.get("family") or "").strip().lower()
    if explicit_fam and explicit_fam in family_set:
        return True

    for key in ("route_template", "path", "url"):
        cand = str(lead.get(key) or "").strip()
        if cand and _path_matches_cluster(cand, route_set=route_set, family_set=family_set):
            return True
    return False


def _count_tracker_metrics(
    tracker: Any,
    *,
    route_set: set[str],
    family_set: set[str],
) -> dict[str, int]:
    """Extract surface counts from either a live `SurfaceFrontierTracker` or its dict snapshot."""
    if tracker is None:
        return {
            "routes": 0,
            "write_ops": 0,
            "opaque_slices": 0,
            "auth_barriers": 0,
            "untested_writes": 0,
        }

    filter_to_cluster = bool((family_set - {"*", "all"}) or route_set)

    def _matches(raw_path: str) -> bool:
        if not filter_to_cluster:
            return True
        return _path_matches_cluster(raw_path, route_set=route_set, family_set=family_set)

    raw_opaque = _get_attr(tracker, "opaque_js_slices", ()) or ()
    opaque_slices = len(list(raw_opaque)) if isinstance(raw_opaque, Sequence) else 0

    disc_routes = _get_attr(tracker, "discovered_routes", None)
    matched_route_tmpls: set[str] = set()
    if isinstance(disc_routes, Mapping):
        for key in disc_routes:
            path = key[1] if isinstance(key, tuple) and len(key) >= 2 else str(key)
            if _matches(str(path)):
                matched_route_tmpls.add(_normalize_route_template(str(path)))
    elif isinstance(disc_routes, Sequence) and not isinstance(disc_routes, (str, bytes)):
        for entry in disc_routes:
            if isinstance(entry, (list, tuple)) and len(entry) >= 2:
                path = str(entry[1])
                if _matches(path):
                    matched_route_tmpls.add(_normalize_route_template(path))

    write_keys: set[tuple[str, str]] = set()
    for attr_name in ("declared_write_ops", "discovered_write_ops"):
        raw_writes = _get_attr(tracker, attr_name, None)
        if isinstance(raw_writes, Mapping):
            for key in raw_writes:
                if isinstance(key, tuple) and len(key) >= 2 and _matches(str(key[1])):
                    write_keys.add((str(key[0]).upper(), _normalize_route_template(str(key[1]))))
        elif isinstance(raw_writes, (set, frozenset, list, tuple)):
            for item in raw_writes:
                if isinstance(item, (list, tuple)) and len(item) >= 2 and _matches(str(item[1])):
                    write_keys.add((str(item[0]).upper(), _normalize_route_template(str(item[1]))))

    untested_writes = 0
    untested_fn = getattr(tracker, "untested_write_ops", None)
    if callable(untested_fn):
        try:
            raw_untested = untested_fn() or ()
        except Exception:
            raw_untested = ()
        untested_writes = sum(1 for op in raw_untested if _matches(str(op)))
    elif isinstance(tracker, Mapping):
        if isinstance(tracker.get("untested_write_ops"), Sequence):
            untested_writes = sum(1 for op in tracker["untested_write_ops"] if _matches(str(op)))
        else:
            tested_keys: set[tuple[str, str]] = set()
            for item in tracker.get("tested_write_ops") or ():
                if isinstance(item, (list, tuple)) and len(item) >= 2:
                    tested_keys.add((str(item[0]).upper(), _normalize_route_template(str(item[1]))))
            untested_writes = sum(1 for k in write_keys if k not in tested_keys)

    barriers = 0
    direct_barriers = _get_attr(tracker, "auth_barriers", 0)
    if isinstance(direct_barriers, (int, float)) and not isinstance(direct_barriers, bool):
        barriers = max(barriers, int(direct_barriers))
    elif isinstance(direct_barriers, (Sequence, set, frozenset, Mapping)) and not isinstance(
        direct_barriers, (str, bytes)
    ):
        barriers = max(barriers, len(direct_barriers))

    soft_denies = _get_attr(tracker, "soft_deny_routes", None)
    if isinstance(soft_denies, Mapping):
        barriers += sum(1 for p in soft_denies if _matches(str(p)))

    ui_fams = _get_attr(tracker, "ui_resource_families", None)
    if isinstance(ui_fams, Mapping):
        for fam, info in ui_fams.items():
            if isinstance(info, Mapping) and info.get("collection_403"):
                if not filter_to_cluster or str(fam).strip().lower() in family_set:
                    barriers += 1

    return {
        "routes": len(matched_route_tmpls),
        "write_ops": len(write_keys),
        "opaque_slices": opaque_slices,
        "auth_barriers": barriers,
        "untested_writes": untested_writes,
    }


def _extract_surface_metrics(
    sres: Mapping[str, Any],
    cluster: Any,
    *,
    route_set: set[str],
    family_set: set[str],
    cluster_routes: Sequence[str],
    cluster_writes: Sequence[str],
) -> dict[str, int]:
    routes_cnt = len(cluster_routes)
    writes_cnt = len(cluster_writes)
    opaque_cnt = int(_get_attr(cluster, "opaque_slices", 0) or 0)
    barriers_cnt = int(_get_attr(cluster, "auth_barriers", 0) or 0)
    untested_writes_cnt = int(sres.get("untested_writes") or 0)

    sc = sres.get("surface_counts")
    if isinstance(sc, Mapping):
        routes_cnt = max(routes_cnt, int(sc.get("routes") or 0))
        writes_cnt = max(writes_cnt, int(sc.get("write_ops") or 0))
        opaque_cnt = max(opaque_cnt, int(sc.get("opaque_slices") or 0))
        barriers_cnt = max(barriers_cnt, int(sc.get("auth_barriers") or 0))
        untested_writes_cnt = max(untested_writes_cnt, int(sc.get("untested_writes") or 0))

    tracker_metrics = _count_tracker_metrics(
        sres.get("surface_tracker"),
        route_set=route_set,
        family_set=family_set,
    )
    return {
        "routes": max(routes_cnt, tracker_metrics["routes"]),
        "write_ops": max(writes_cnt, tracker_metrics["write_ops"]),
        "opaque_slices": max(opaque_cnt, tracker_metrics["opaque_slices"]),
        "auth_barriers": max(barriers_cnt, tracker_metrics["auth_barriers"]),
        "untested_writes": max(untested_writes_cnt, tracker_metrics["untested_writes"]),
    }


def _build_retry_objective(
    *,
    shard_id: str,
    cluster_name: str,
    triggers: Sequence[str],
    lead_ids: Sequence[str],
    fact_ids: Sequence[str],
    metrics: Mapping[str, int],
) -> str:
    parts: list[str] = []
    if "lead_followup" in triggers:
        lead_desc = ", ".join(lead_ids) if lead_ids else "unpromoted shard leads"
        parts.append(f"verify active leads ({lead_desc})")
    if "late_shared_fact_unlocked" in triggers:
        fact_desc = ", ".join(fact_ids) if fact_ids else "late shared facts"
        parts.append(f"chain newly unlocked shared facts ({fact_desc})")
    if "high_surface_zero_findings" in triggers:
        gaps: list[str] = []
        if metrics.get("untested_writes", 0) > 0:
            gaps.append(f"untested_writes={metrics['untested_writes']}")
        if metrics.get("opaque_slices", 0) > 0:
            gaps.append(f"opaque_slices={metrics['opaque_slices']}")
        if metrics.get("auth_barriers", 0) > 0:
            gaps.append(f"auth_barriers={metrics['auth_barriers']}")
        if metrics.get("routes", 0) > 0:
            gaps.append(f"routes={metrics['routes']}")
        if metrics.get("write_ops", 0) > 0:
            gaps.append(f"write_ops={metrics['write_ops']}")
        parts.append(f"close high-surface 0-finding gaps ({', '.join(gaps) or 'surface'})")
    return (
        f"Stage 2.5 verification for {shard_id} ({cluster_name}) "
        f"[triggers: {', '.join(triggers)}]: {'; '.join(parts)}."
    )


def evaluate_stage25_retry_candidates(
    *,
    clusters: Sequence[Any],
    shard_results: Sequence[dict[str, Any]],
    active_leads: Sequence[dict[str, Any]],
    shared_facts: Any,
    remaining_http: int,
    remaining_tokens: int,
    remaining_seconds: float,
    stage3_http_reserve: int,
    stage3_token_reserve: int,
    retry_budget_ratio: float = 0.15,
    max_retry_shards: int = 2,
    max_shard_retries: int = 1,
    retry_model: str = "",
    primary_model: str = "",
    default_shard_turns: int = 16,
    sampling_seed_base: int = 20261127,
) -> list[dict[str, Any]]:
    """Deterministically rank and allocate Stage 2.5 retry shards under Stage 3 reserves."""
    if (
        int(max_shard_retries) <= 0
        or int(max_retry_shards) <= 0
        or float(retry_budget_ratio) <= 0.0
    ):
        return []
    if int(remaining_http) <= int(stage3_http_reserve) + 4:
        return []
    if int(remaining_tokens) <= int(stage3_token_reserve) + 12_000:
        return []
    if float(remaining_seconds) <= 15.0:
        return []

    cluster_by_id: dict[str, Any] = {}
    for cluster in clusters or ():
        sid = str(_get_attr(cluster, "shard_id", "") or "").strip()
        if sid:
            cluster_by_id[sid] = cluster
    if not cluster_by_id:
        return []

    unpromoted_leads = [
        lead
        for lead in (active_leads or ())
        if isinstance(lead, Mapping)
        and not lead.get("promoted_to_finding_id")
        and str(lead.get("status") or "").strip().lower() != "promoted"
    ]

    candidates: list[dict[str, Any]] = []
    for sres in shard_results or ():
        if not isinstance(sres, Mapping):
            continue
        shard_id = str(sres.get("shard_id") or "").strip()
        cluster = cluster_by_id.get(shard_id)
        if cluster is None:
            continue
        status = str(sres.get("status") or "").strip().lower()
        if status not in _RETRYABLE_STAGE2_STATUSES:
            continue
        if int(sres.get("retry_count") or 0) >= int(max_shard_retries):
            continue

        route_set, family_set, families, cluster_routes, cluster_writes = _cluster_route_and_family_sets(cluster)
        if not families and isinstance(sres.get("families"), Sequence):
            families = [str(f).strip() for f in sres["families"] if str(f).strip()]
            family_set = {f.lower() for f in families}
        cluster_name = str(_get_attr(cluster, "name", "") or sres.get("name") or shard_id)

        triggers: list[str] = []
        priority_score = 0

        matched_leads = [
            lead
            for lead in unpromoted_leads
            if _lead_matches_shard(
                lead,
                shard_id=shard_id,
                route_set=route_set,
                family_set=family_set,
            )
        ]
        lead_ids = list(dict.fromkeys(
            str(ld.get("lead_id") or "").strip()
            for ld in matched_leads
            if str(ld.get("lead_id") or "").strip()
        ))
        if matched_leads:
            triggers.append("lead_followup")
            priority_score += 60

        fact_ids: list[str] = []
        if shared_facts is not None:
            closed_at_seq = int(sres.get("closed_at_seq") or 0)
            late_raw = shared_facts.facts_after(
                closed_at_seq,
                exclude_shard=shard_id,
                families=families,
            )
            late_high_signal = [
                f
                for f in (late_raw or ())
                if isinstance(f, Mapping)
                and str(f.get("fact_type") or "").strip().lower() in HIGH_SIGNAL_RETRY_FACT_TYPES
            ]
            if late_high_signal:
                triggers.append("late_shared_fact_unlocked")
                priority_score += 50
                fact_ids = list(dict.fromkeys(
                    str(f.get("fact_id") or "").strip()
                    for f in late_high_signal
                    if str(f.get("fact_id") or "").strip()
                ))

        if "lead_followup" in triggers and "late_shared_fact_unlocked" in triggers:
            priority_score += 40

        metrics = _extract_surface_metrics(
            sres,
            cluster,
            route_set=route_set,
            family_set=family_set,
            cluster_routes=cluster_routes,
            cluster_writes=cluster_writes,
        )
        confirmed_count = len(sres.get("findings") or ())
        high_surface = (
            metrics["routes"] >= 4
            or metrics["write_ops"] >= 2
            or metrics["opaque_slices"] >= 1
            or metrics["auth_barriers"] >= 2
        )
        quota = int(sres.get("shard_token_quota") or 0)
        tokens_used = int(sres.get("tokens") or 0)
        stall_evidence = (
            status in {"max_turns_reached", "budget_exhausted", "http_budget_exhausted"}
            or int(sres.get("epoch_advancements") or 0) >= 1
            or (quota > 0 and tokens_used >= int(quota * 0.80))
        )
        if confirmed_count == 0 and high_surface and stall_evidence:
            triggers.append("high_surface_zero_findings")
            priority_score += 30

        if not triggers:
            continue

        candidates.append({
            "shard_id": shard_id,
            "cluster_name": cluster_name,
            "families": families,
            "priority_score": priority_score,
            "triggers": triggers,
            "lead_ids": lead_ids,
            "fact_ids": fact_ids,
            "metrics": metrics,
        })

    if not candidates:
        return []

    candidates.sort(key=lambda item: (-int(item["priority_score"]), str(item["shard_id"])))
    selected = candidates[: max(1, int(max_retry_shards))]

    avail_tokens = max(0, int(remaining_tokens) - int(stage3_token_reserve))
    eff_ratio = min(1.0, max(0.0, float(retry_budget_ratio)))
    target_pool = min(
        avail_tokens,
        max(12_000 * len(selected), int(avail_tokens * eff_ratio)),
    )
    per_shard_quota = max(12_000, int(target_pool / max(1, len(selected))))
    allocated_max_turns = max(6, min(max(8, int(default_shard_turns)), 16))
    http_reserve_floor = int(stage3_http_reserve)
    eff_retry_model = str(retry_model or primary_model or "")

    decisions: list[dict[str, Any]] = []
    remaining_pool = target_pool
    for idx, cand in enumerate(selected):
        if remaining_pool < 12_000:
            break
        alloc_tokens = max(12_000, min(per_shard_quota, remaining_pool))
        remaining_pool -= alloc_tokens
        objective = _build_retry_objective(
            shard_id=cand["shard_id"],
            cluster_name=cand["cluster_name"],
            triggers=cand["triggers"],
            lead_ids=cand["lead_ids"],
            fact_ids=cand["fact_ids"],
            metrics=cand["metrics"],
        )
        decisions.append({
            "schema": "agentic-stage25-decision/1",
            "eligible": True,
            "shard_id": cand["shard_id"],
            "cluster_name": cand["cluster_name"],
            "families": list(cand["families"]),
            "priority_score": int(cand["priority_score"]),
            "triggers": list(cand["triggers"]),
            "lead_ids": list(cand["lead_ids"]),
            "fact_ids": list(cand["fact_ids"]),
            "retry_model": eff_retry_model,
            "allocated_token_quota": alloc_tokens,
            "allocated_max_turns": allocated_max_turns,
            "http_reserve_floor": http_reserve_floor,
            "sampling_seed": int(sampling_seed_base) + idx * 101,
            "objective": objective,
        })
    return decisions


def _lookup_receipt(receipts: Any, receipt_id: str) -> dict[str, Any] | None:
    if receipts is None:
        return None
    rid = str(receipt_id or "").strip()
    if not rid:
        return None
    get_fn = getattr(receipts, "get", None)
    if callable(get_fn):
        try:
            rec = get_fn(rid)
        except (KeyError, ValueError, TypeError, OSError):
            return None
        return dict(rec) if isinstance(rec, Mapping) else None
    if isinstance(receipts, Mapping):
        rec = receipts.get(rid)
        return dict(rec) if isinstance(rec, Mapping) else None
    return None


def _extract_stage_label(rejection: Mapping[str, Any]) -> str:
    explicit = str(rejection.get("stage") or "").strip()
    if explicit:
        return explicit
    stages = rejection.get("stages")
    if isinstance(stages, Mapping):
        for k, v in stages.items():
            val_s = str(v or "").strip()
            if any(tok in val_s.lower() for tok in ("fail", "refut", "decept", "reject")):
                return f"{k}:{val_s}"
        for k, v in stages.items():
            val_s = str(v or "").strip()
            if val_s:
                return f"{k}:{val_s}"
    return ""


def _header_blob_from_receipt(receipt: Mapping[str, Any]) -> tuple[str, str]:
    raw_headers = receipt.get("response_headers")
    if raw_headers is None:
        raw_headers = receipt.get("headers")
    lines: list[str] = []
    ctype = str(receipt.get("content_type") or "").strip().lower()
    if isinstance(raw_headers, Mapping):
        for k, v in raw_headers.items():
            ks = str(k).strip()
            vs = str(v).strip()
            lines.append(f"{ks}: {vs}")
            if ks.lower() == "content-type" and not ctype:
                ctype = vs.lower()
    elif isinstance(raw_headers, str):
        for ln in raw_headers.splitlines():
            clean = ln.strip()
            if clean:
                lines.append(clean)
                if clean.lower().startswith("content-type:") and not ctype:
                    ctype = clean.split(":", 1)[1].strip().lower()
    return "\n".join(lines).lower(), ctype


def _detect_receipt_waf_hint(receipt: Mapping[str, Any]) -> dict[str, Any] | None:
    try:
        status = int(receipt.get("status") or 0)
    except (TypeError, ValueError):
        status = 0
    explicit_waf = bool(receipt.get("waf_blocked"))
    if not explicit_waf and status not in _WAF_STATUSES and status != 503:
        return None

    header_low, ctype = _header_blob_from_receipt(receipt)
    body_low = str(receipt.get("body") or "").lower()

    vendor = ""
    for marker, vname in _WAF_HEADER_MARKERS:
        if marker in header_low:
            vendor = vname
            break
    if not vendor and "cf-ray" in header_low and any(
        tok in body_low for tok in ("cloudflare", "attention required", "error 1020", "request blocked")
    ):
        vendor = "cloudflare"
    if not vendor:
        for marker, vname in _WAF_BODY_MARKERS:
            if marker in body_low:
                vendor = vname
                break

    is_json_body = False
    stripped_body = body_low.strip()
    if "json" in ctype or (stripped_body.startswith("{") and stripped_body.endswith("}")):
        try:
            parsed = json.loads(stripped_body)
            is_json_body = isinstance(parsed, dict)
        except ValueError:
            is_json_body = False

    if status == 429:
        return {"status": 429, "vendor": vendor or "rate_limiter"}
    if explicit_waf or vendor:
        return {"status": status, "vendor": vendor or "generic"}
    if status == 406 and not is_json_body:
        return {"status": 406, "vendor": "edge_waf"}
    if status == 403 and not is_json_body and ("html" in ctype or "<html" in body_low[:512]):
        if any(tok in body_low for tok in ("forbidden", "access denied", "blocked")):
            return {"status": 403, "vendor": "edge_waf"}
    return None


def _extract_request_params(receipt: Mapping[str, Any]) -> tuple[set[str], str]:
    params: set[str] = set()
    raw_url = str(receipt.get("url") or receipt.get("path") or "").strip()
    url_q = urlsplit(raw_url).query
    rec_q = str(receipt.get("query") or "").strip()
    query_str = rec_q or url_q
    for k, _ in parse_qsl(query_str, keep_blank_values=True):
        if k.strip():
            params.add(k.strip())

    req_body = str(receipt.get("request_body") or "").strip()
    if req_body.startswith("{"):
        try:
            parsed_body = json.loads(req_body)
        except ValueError:
            parsed_body = None
        if isinstance(parsed_body, Mapping):
            for k in parsed_body:
                if str(k).strip():
                    params.add(str(k).strip())
    elif req_body and "=" in req_body and not req_body.startswith(("<", "[")):
        for k, _ in parse_qsl(req_body, keep_blank_values=True):
            if k.strip():
                params.add(k.strip())
    vector_sig = f"{query_str}|{req_body[:160]}"
    return params, vector_sig


def _render_dead_end_digest_block(
    *,
    deception_traps: Sequence[Mapping[str, Any]],
    oracle_refutations: Sequence[Mapping[str, Any]],
    waf_blocked_patterns: Sequence[Mapping[str, Any]],
    untried_angles: Sequence[str],
    probed_no_delta_routes: Sequence[Mapping[str, Any]],
    max_chars: int,
    secret_values: Sequence[str],
) -> str:
    eff_max = max(200, int(max_chars))
    candidate_lines: list[str] = []

    for trap in deception_traps[:4]:
        candidate_lines.append(
            f"- DECEPTION_TRAP: {trap['class_type']} {trap['method']} {trap['route_template']} "
            f"(actor={trap['actor']}) — do not claim false positive"
        )
    for ref in oracle_refutations[:6]:
        stage_part = f" stage={ref['stage']}" if ref.get("stage") else ""
        cnt_part = f" x{ref['count']}" if int(ref.get("count") or 1) > 1 else ""
        candidate_lines.append(
            f"- REFUTED: {ref['class_type']} {ref['method']} {ref['route_template']} "
            f"actor={ref['actor']} verdict={ref['verdict']}{stage_part}{cnt_part} — try orthogonal vector"
        )
    for waf in waf_blocked_patterns[:4]:
        route = waf.get("route_template") or "/"
        method = waf.get("method") or "HTTP"
        vendor = waf.get("vendor") or "waf"
        status = waf.get("status") or 403
        candidate_lines.append(
            f"- WAF_BLOCK: {method} {route} ({status}/{vendor}) — {waf.get('pivot_guidance')}"
        )
    for angle in untried_angles[:5]:
        candidate_lines.append(f"- UNTRIED: {angle}")
    for nd in probed_no_delta_routes[:4]:
        actors_s = ",".join(nd.get("actors_tested") or ()) or "none"
        params_s = ",".join(nd.get("params_tested") or ()) or "none"
        candidate_lines.append(
            f"- NO_DELTA: ({nd['method']}, {nd['route_template']}, actors=[{actors_s}] params=[{params_s}] -> {nd['outcome']})"
        )

    if not candidate_lines:
        candidate_lines.append("- No refuted angles, deception traps, or WAF blocks recorded yet.")

    lines_out = [_DIGEST_HEADER]
    used_len = len(_DIGEST_HEADER)
    for raw_line in candidate_lines:
        clean_line = _scrub_text(raw_line, secret_values, single_line=True)
        if not clean_line:
            continue
        if used_len + 1 + len(clean_line) <= eff_max:
            lines_out.append(clean_line)
            used_len += 1 + len(clean_line)
            continue
        if len(lines_out) == 1:
            avail = eff_max - len(_DIGEST_HEADER) - 4
            if avail > 10:
                lines_out.append(clean_line[:avail].rstrip() + "...")
        break

    rendered = "\n".join(lines_out)
    rendered = _scrub_text(rendered, secret_values, single_line=False)
    if len(rendered) > eff_max:
        rendered = rendered[: eff_max - 3].rstrip() + "..."
    return rendered


def build_dead_end_digest(
    *,
    shard_id: str,
    receipts: Any,
    shard_receipt_ids: Sequence[str] = (),
    oracle_rejections: Sequence[dict[str, Any]] = (),
    waf_pivot: Any = None,
    surface_tracker: Any = None,
    cluster_families: Sequence[str] = (),
    active_actors: Sequence[str] = (),
    newly_unlocked_facts: Sequence[dict[str, Any]] = (),
    max_chars: int = 1200,
    secret_values: Sequence[str] = (),
) -> dict[str, Any]:
    """Build a secret-scrubbed, strictly bounded dead-end digest for Stage 2.5 fresh context."""
    _ = active_actors  # Reserved for caller compatibility
    clean_shard_id = _scrub_text(shard_id, secret_values)
    fam_filter = {str(f).strip().lower() for f in (cluster_families or ()) if str(f).strip()}
    if "*" in fam_filter or "all" in fam_filter:
        fam_filter = set()

    # 1. Group oracle refutations and deception traps
    ref_counts: dict[tuple[str, str, str, str, str, str], int] = {}
    trap_counts: dict[tuple[str, str, str, str, str], dict[str, Any]] = {}
    for rej in oracle_rejections or ():
        if not isinstance(rej, Mapping):
            continue
        verdict = _scrub_text(
            rej.get("verdict") or rej.get("oracle_verdict") or "REFUTED",
            secret_values,
        ).upper() or "REFUTED"
        is_deception = bool(rej.get("deception_detected")) or verdict == "DECEPTION_DETECTED"
        cls_type = _scrub_text(rej.get("class_type") or rej.get("vuln_class") or "unknown", secret_values)
        method = _scrub_text(rej.get("method") or "GET", secret_values).upper() or "GET"
        raw_route = str(rej.get("route_template") or rej.get("path") or rej.get("url") or "/")
        route_tmpl = _scrub_text(_normalize_route_template(raw_route), secret_values)
        actor = _scrub_text(rej.get("actor") or rej.get("actor_alias") or "anon", secret_values)
        stage = _scrub_text(_extract_stage_label(rej), secret_values)

        if is_deception:
            t_key = (cls_type, method, route_tmpl, actor, stage)
            existing_trap = trap_counts.get(t_key)
            if existing_trap is None:
                trap_counts[t_key] = {
                    "class_type": cls_type,
                    "method": method,
                    "route_template": route_tmpl,
                    "actor": actor,
                    "verdict": "DECEPTION_DETECTED",
                    "stage": stage,
                    "reason": _scrub_text(rej.get("reason") or "deception detected", secret_values)[:160],
                    "count": 1,
                }
            else:
                existing_trap["count"] += 1
        else:
            r_key = (cls_type, method, route_tmpl, actor, verdict, stage)
            ref_counts[r_key] = ref_counts.get(r_key, 0) + 1

    oracle_refutations = [
        {
            "class_type": k[0],
            "method": k[1],
            "route_template": k[2],
            "actor": k[3],
            "verdict": k[4],
            "stage": k[5],
            "count": count,
        }
        for k, count in sorted(
            ref_counts.items(),
            key=lambda kv: (-kv[1], kv[0][0], kv[0][2], kv[0][1], kv[0][3]),
        )
    ]
    deception_traps = sorted(
        trap_counts.values(),
        key=lambda item: (-int(item["count"]), item["class_type"], item["route_template"]),
    )

    # 2. Inspect shard receipts for WAF blocks & probed no-delta routes
    waf_grouped: dict[tuple[str, str, int, str], int] = {}
    route_probes: dict[tuple[str, str], list[dict[str, Any]]] = {}
    for rid in shard_receipt_ids or ():
        rec = _lookup_receipt(receipts, str(rid))
        if rec is None:
            continue
        method = _scrub_text(rec.get("method") or "GET", secret_values).upper() or "GET"
        raw_url = str(rec.get("url") or rec.get("path") or "/")
        route_tmpl = _scrub_text(_normalize_route_template(raw_url), secret_values)

        waf_hit = _detect_receipt_waf_hint(rec)
        if waf_hit is not None:
            w_key = (method, route_tmpl, int(waf_hit["status"]), str(waf_hit["vendor"]))
            waf_grouped[w_key] = waf_grouped.get(w_key, 0) + 1

        route_probes.setdefault((method, route_tmpl), []).append(rec)

    pivot_advice_default = (
        "pivot to WAF-blind checks (BOLA/BFLA replay_as, JSON mass assignment, "
        "concurrent_check race, or header/encoding variants) rather than repeating signature probes"
    )
    waf_guidance_str = ""
    waf_summary_meta: dict[str, Any] = {}
    if waf_pivot is not None:
        if callable(getattr(waf_pivot, "guidance", None)):
            try:
                waf_guidance_str = _scrub_text(waf_pivot.guidance() or "", secret_values)[:220]
            except Exception:
                waf_guidance_str = ""
        if callable(getattr(waf_pivot, "summary", None)):
            try:
                raw_sum = waf_pivot.summary()
                if isinstance(raw_sum, Mapping):
                    waf_summary_meta = dict(raw_sum)
            except Exception:
                waf_summary_meta = {}
        elif isinstance(waf_pivot, Mapping):
            waf_summary_meta = dict(waf_pivot)
            waf_guidance_str = _scrub_text(waf_pivot.get("guidance") or "", secret_values)[:220]

    eff_pivot_guidance = waf_guidance_str or pivot_advice_default
    waf_blocked_patterns: list[dict[str, Any]] = [
        {
            "method": k[0],
            "route_template": k[1],
            "status": k[2],
            "vendor": _scrub_text(k[3], secret_values),
            "count": count,
            "pivot_guidance": eff_pivot_guidance,
        }
        for k, count in sorted(waf_grouped.items(), key=lambda kv: (-kv[1], kv[0][1], kv[0][0]))
    ]
    if not waf_blocked_patterns and waf_summary_meta:
        blocked_paths = [str(p) for p in (waf_summary_meta.get("blocked_paths") or ()) if str(p).strip()]
        vendors_map = waf_summary_meta.get("vendors") or {}
        top_vendor = "generic"
        if isinstance(vendors_map, Mapping) and vendors_map:
            top_vendor = max(sorted(vendors_map), key=lambda v: int(vendors_map[v] or 0))
        matching_paths = [
            p
            for p in blocked_paths
            if not fam_filter or _extract_family_and_subfamily(p)[0] in fam_filter
        ]
        if matching_paths or waf_summary_meta.get("should_pivot"):
            for bp in (matching_paths or blocked_paths[:1] or ["/"]):
                waf_blocked_patterns.append({
                    "method": "HTTP",
                    "route_template": _scrub_text(_normalize_route_template(bp), secret_values),
                    "status": 403,
                    "vendor": _scrub_text(top_vendor, secret_values),
                    "count": int(waf_summary_meta.get("total_blocks") or 1),
                    "pivot_guidance": eff_pivot_guidance,
                })

    probed_no_delta_routes: list[dict[str, Any]] = []
    for (method, route_tmpl), recs in sorted(route_probes.items()):
        if len(recs) < 2:
            continue
        statuses = {int(r.get("status") or 0) for r in recs}
        if len(statuses) != 1:
            continue
        single_status = next(iter(statuses))
        actors_tested: set[str] = set()
        params_tested: set[str] = set()
        distinct_vectors: set[tuple[str, str]] = set()
        body_hashes: set[str] = set()
        for r in recs:
            actor = _scrub_text(r.get("actor") or "anon", secret_values) or "anon"
            actors_tested.add(actor)
            r_params, vec_sig = _extract_request_params(r)
            params_tested.update(_scrub_text(p, secret_values) for p in r_params if p)
            distinct_vectors.add((actor, vec_sig))
            bhash = str(r.get("response_sha256") or "")
            if not bhash:
                bhash = str(len(str(r.get("body") or "")))
            body_hashes.add(bhash)

        if len(actors_tested) < 2 and len(params_tested) < 2 and len(distinct_vectors) < 2:
            continue
        if 200 <= single_status < 300 and len(body_hashes) > 1:
            continue
        probed_no_delta_routes.append({
            "method": method,
            "route_template": route_tmpl,
            "status": single_status,
            "actors_tested": sorted(actors_tested),
            "params_tested": sorted(params_tested),
            "probe_count": len(recs),
            "outcome": f"HTTP {single_status} unchanged across {len(recs)} probes",
        })

    # 3. Collect untried angles from surface_tracker + newly_unlocked_facts
    untried_angles: list[str] = []
    seen_angles: set[str] = set()

    def _add_angle(text: str) -> None:
        clean = _scrub_text(text, secret_values, single_line=True)
        if clean and clean not in seen_angles:
            seen_angles.add(clean)
            untried_angles.append(clean)

    for fact in newly_unlocked_facts or ():
        if not isinstance(fact, Mapping):
            continue
        fid = str(fact.get("fact_id") or "").strip()
        ftype = str(fact.get("fact_type") or "").strip()
        fsummary = str(fact.get("summary") or fact.get("canonical_key") or "").strip()
        if fsummary:
            prefix = f"fact {fid} [{ftype}]" if fid else f"fact [{ftype}]"
            _add_angle(f"{prefix}: {fsummary}")

    if surface_tracker is not None:
        untested_fn = getattr(surface_tracker, "untested_write_ops", None)
        raw_writes: Sequence[str] = ()
        if callable(untested_fn):
            try:
                raw_writes = untested_fn() or ()
            except Exception:
                raw_writes = ()
        elif isinstance(surface_tracker, Mapping) and isinstance(surface_tracker.get("untested_write_ops"), Sequence):
            raw_writes = surface_tracker["untested_write_ops"]
        for wop in raw_writes:
            w_str = str(wop or "").strip()
            if not w_str:
                continue
            if fam_filter:
                fam, sub = _extract_family_and_subfamily(w_str)
                if fam not in fam_filter and (sub is None or sub not in fam_filter):
                    continue
            _add_angle(f"untested write: {w_str}")

        raw_slices = _get_attr(surface_tracker, "opaque_js_slices", ()) or ()
        if isinstance(raw_slices, Sequence) and not isinstance(raw_slices, (str, bytes)):
            for slc in raw_slices:
                if not isinstance(slc, Mapping):
                    continue
                rid = str(slc.get("receipt_id") or "").strip()
                url_path = urlsplit(str(slc.get("url") or "")).path or "js"
                c_start = int(slc.get("char_start") or 0)
                c_end = int(slc.get("char_end") or 0)
                anchor = str(slc.get("anchor") or slc.get("region_id") or "slice")
                _add_angle(f"opaque_js {rid} {url_path}@{c_start}+{max(0, c_end - c_start)} ({anchor})".strip())

    rendered_prompt_block = _render_dead_end_digest_block(
        deception_traps=deception_traps,
        oracle_refutations=oracle_refutations,
        waf_blocked_patterns=waf_blocked_patterns,
        untried_angles=untried_angles,
        probed_no_delta_routes=probed_no_delta_routes,
        max_chars=max_chars,
        secret_values=secret_values,
    )

    return {
        "schema": "agentic-dead-end-digest/1",
        "shard_id": clean_shard_id,
        "oracle_refutations": oracle_refutations,
        "deception_traps": deception_traps,
        "waf_blocked_patterns": waf_blocked_patterns,
        "probed_no_delta_routes": probed_no_delta_routes,
        "untried_angles": untried_angles,
        "rendered_prompt_block": rendered_prompt_block,
    }


def _strip_shard_scope_suffix(system_prompt: str) -> str:
    text = str(system_prompt or "")
    for marker in ("\n\nSUBSYSTEM SHARD SCOPE (", "\n\nSTAGE 2.5 FOCUSED VERIFICATION PASS ("):
        if marker in text:
            text = text.split(marker, 1)[0]
    return text.rstrip()


def _format_actor_handles(active_actors: Sequence[dict[str, Any]] | Sequence[str]) -> str:
    handles: list[str] = []
    for item in active_actors or ():
        if isinstance(item, Mapping):
            alias = _scrub_text(item.get("alias") or "")
            if not alias:
                continue
            role = _scrub_text(item.get("role") or "actor")
            tenant = _scrub_text(item.get("tenant") or "")
            handles.append(f"{alias} ({role}, tenant={tenant})" if tenant else f"{alias} ({role})")
        else:
            alias = _scrub_text(item)
            if alias:
                handles.append(f"{alias} (actor)")
    return ", ".join(handles) if handles else "anon (anonymous)"


def build_stage25_retry_prompts(
    *,
    cluster: Any,
    candidate: dict[str, Any],
    base_system_prompt: str,
    shared_facts_snapshot: str,
    dead_end_digest: dict[str, Any],
    active_actors: Sequence[dict[str, Any]] | Sequence[str],
    state_banner: str = "",
    active_leads_for_shard: Sequence[dict[str, Any]] = (),
) -> tuple[str, str]:
    """Build clean fresh-context Stage 2.5 system and user prompts without prior Stage 2 history."""
    shard_id = str(_get_attr(cluster, "shard_id", "") or candidate.get("shard_id") or "shard").strip()
    cluster_name = str(_get_attr(cluster, "name", "") or candidate.get("cluster_name") or shard_id).strip()
    families = [str(f).strip() for f in (_get_attr(cluster, "families", None) or candidate.get("families") or ()) if str(f).strip()]
    routes = [str(r).strip() for r in (_get_attr(cluster, "routes", None) or ()) if str(r).strip()][:25]
    writes = [str(w).strip() for w in (_get_attr(cluster, "write_ops", None) or ()) if str(w).strip()][:15]
    objects = [str(o).strip() for o in (_get_attr(cluster, "objects", None) or ()) if str(o).strip()][:15]
    params_map = _get_attr(cluster, "params", None) or {}
    param_lines: list[str] = []
    if isinstance(params_map, Mapping):
        for tmpl, pnames in sorted(params_map.items())[:15]:
            clean_p = [str(p).strip() for p in (pnames or ()) if str(p).strip()][:8]
            if clean_p:
                param_lines.append(f"  - {tmpl}: {', '.join(clean_p)}")

    clean_base = _strip_shard_scope_suffix(base_system_prompt)
    scope_sections = [
        f"STAGE 2.5 FOCUSED VERIFICATION PASS ({shard_id}: {cluster_name}):",
        f"- Assigned resource families: {', '.join(families) or '(all)'}",
        "- This is a fresh-context second-pass verification focused strictly on unconfirmed leads, late shared facts, and orthogonal attack vectors.",
        "- Do NOT repeat refuted probes or deception traps listed in the Dead-End Digest; pivot to orthogonal vulnerability classes, alternate actors, HTTP methods, headers, or parameter encodings.",
        "- Assigned routes:\n  " + ("\n  ".join(routes) if routes else "(none)"),
    ]
    if writes:
        scope_sections.append("- Assigned write operations:\n  " + "\n  ".join(writes))
    if objects:
        scope_sections.append("- Assigned concrete objects:\n  " + "\n  ".join(objects))
    if param_lines:
        scope_sections.append("- Assigned parameters:\n" + "\n".join(param_lines))
    scope_sections.append(
        "- Call `record_finding` immediately as soon as any vulnerability is confirmed with proof + comparative control receipts, and call `finish` when this Stage 2.5 pass is complete."
    )
    sys_prompt = (clean_base + "\n\n" + "\n".join(scope_sections)).strip()

    # Block 1: Concrete Stage 2.5 trigger & objective + lead details
    triggers_str = ", ".join(str(t) for t in (candidate.get("triggers") or ())) or "manual"
    objective = _scrub_text(
        candidate.get("objective") or f"Verify remaining leads and orthogonal attack paths in {shard_id}.",
        single_line=True,
    )
    lead_lines: list[str] = []
    for lead in (active_leads_for_shard or ())[:6]:
        if not isinstance(lead, Mapping):
            continue
        lid = _scrub_text(lead.get("lead_id") or "lead")
        sig = _scrub_text(lead.get("signal_type") or "")
        cls_t = _scrub_text(lead.get("class_type") or "")
        method = _scrub_text(lead.get("method") or "GET").upper()
        route = _scrub_text(lead.get("route_template") or lead.get("path") or "/")
        blocker = _scrub_text(lead.get("verification_blocker") or "")[:120]
        hint = _scrub_text(lead.get("suggested_manual_verification") or "")[:140]
        proofs = ",".join(str(r) for r in (lead.get("proof_receipt_ids") or ())[:3])
        ctrls = ",".join(str(r) for r in (lead.get("control_receipt_ids") or ())[:2])
        line = f"  - {lid} [{cls_t}/{sig}] {method} {route} proofs=[{proofs}] controls=[{ctrls}]"
        if blocker:
            line += f" | blocker={blocker}"
        if hint:
            line += f" | next={hint}"
        lead_lines.append(line)

    block1_lines = [
        f"[STAGE 2.5 TRIGGER & OBJECTIVE] shard={shard_id} | triggers={triggers_str} | priority={int(candidate.get('priority_score') or 0)}",
        f"Objective: {objective}",
    ]
    if lead_lines:
        block1_lines.append("Active Leads to Verify/Promote:")
        block1_lines.extend(lead_lines)
    block1 = "\n".join(block1_lines)

    # Block 2: SharedFactGraph snapshot + safe actor handles
    facts_text = _scrub_text(shared_facts_snapshot or "", single_line=False).strip()
    if not facts_text:
        facts_text = "(no shared facts recorded yet)"
    actors_text = _format_actor_handles(active_actors)
    block2 = (
        "[SHARED FACTS & ACTIVE ACTORS]\n"
        f"Actors: {actors_text}\n"
        f"{facts_text}"
    )

    # Block 3: DeadEndDigest + GET cache reminder
    raw_digest = str((dead_end_digest or {}).get("rendered_prompt_block") or "").strip()
    clean_digest = _scrub_text(raw_digest, single_line=False)
    if not clean_digest:
        clean_digest = f"{_DIGEST_HEADER}\n- No prior refutations or WAF blocks recorded."
    if len(clean_digest) > 1200:
        clean_digest = clean_digest[:1197].rstrip() + "..."
    cache_note = (
        "Cache Note: Unchanged GET/HEAD calls hit cache (`cached=True`, 0 HTTP cost); "
        "pass `force=true` or use new methods, actors, or payloads when re-probing mutated routes."
    )
    block3 = f"{clean_digest}\n{cache_note}"

    clean_banner = ""
    if str(state_banner or "").strip():
        clean_banner = "\n" + str(state_banner).lstrip("\n")

    user_prompt = f"{block1}\n\n{block2}\n\n{block3}{clean_banner}"
    return sys_prompt, user_prompt
