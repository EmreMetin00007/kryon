"""Read-only passive HTTP WAF/CDN block classifier for stored receipts.

Distinguishes upstream WAF/CDN block pages from ordinary application-level
403/401/429 responses. Purely offline with zero network calls.
"""
from __future__ import annotations

import json
from pathlib import Path
import sys
from typing import Any, Callable

_REPO_ROOT = Path(__file__).resolve().parent.parent
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

_EVALUATED_STATUSES = frozenset({403, 406, 429, 503})

_EXPLICIT_BLOCK_HEADERS: tuple[tuple[str, str], ...] = (
    ("cf-mitigated", "cloudflare"),
    ("cf-error-details", "cloudflare"),
    ("x-amzn-waf", "aws_waf"),
    ("x-wa-info", "f5_big_ip_asm"),
    ("server: mod_security", "modsecurity"),
    ("mod_security", "modsecurity"),
    ("x-sucuri-id", "sucuri"),
    ("sucuri/cloudproxy", "sucuri"),
    ("fortiwafsid", "fortinet_fortiweb"),
    ("barra_counter_session", "barracuda"),
)

_VENDOR_BODY_SIGNATURES: tuple[tuple[str, str], ...] = (
    ("attention required! | cloudflare", "cloudflare"),
    ("cf-error-details", "cloudflare"),
    ("error 1020", "cloudflare"),
    ("this error was generated by mod_security", "modsecurity"),
    ("mod_security", "modsecurity"),
    ("modsecurity", "modsecurity"),
    ("the requested url was rejected", "f5_big_ip_asm"),
    ("access denied - sucuri website firewall", "sucuri"),
    ("_incapsula_resource", "imperva_incapsula"),
    ("incapsula", "imperva_incapsula"),
    ("request blocked by aws", "aws_waf"),
    ("aws waf", "aws_waf"),
    ("akamaighost", "akamai"),
    ("akamai", "akamai"),
    ("generated by wordfence", "wordfence"),
    ("your access to this site has been limited", "wordfence"),
    ("fortiweb", "fortinet_fortiweb"),
    ("fastly error", "fastly"),
)

_GENERIC_WAF_BODY_SIGNATURES: tuple[str, ...] = (
    "the requested url was rejected",
    "request blocked",
    "attention required",
    "incident id",
    "support id",
    "web application firewall",
)

_WAF_PROFILES_LOADED = False
_CLASSIFY_HTTP: Callable[..., dict[str, Any]] | None = None
_FINGERPRINT_CHANNELS: Callable[..., tuple[str, int, list[str]]] | None = None


def _load_waf_profiles() -> tuple[
    Callable[..., dict[str, Any]] | None,
    Callable[..., tuple[str, int, list[str]]] | None,
]:
    """Lazily import passive classifiers from kryon_core.waf.waf_profiles."""
    global _WAF_PROFILES_LOADED, _CLASSIFY_HTTP, _FINGERPRINT_CHANNELS
    if _WAF_PROFILES_LOADED:
        return _CLASSIFY_HTTP, _FINGERPRINT_CHANNELS
    _WAF_PROFILES_LOADED = True
    try:
        if str(_REPO_ROOT) not in sys.path:
            sys.path.insert(0, str(_REPO_ROOT))
        from kryon_core.waf.waf_profiles import classify_http, fingerprint_channels

        _CLASSIFY_HTTP = classify_http
        _FINGERPRINT_CHANNELS = fingerprint_channels
    except Exception:
        _CLASSIFY_HTTP = None
        _FINGERPRINT_CHANNELS = None
    return _CLASSIFY_HTTP, _FINGERPRINT_CHANNELS


def _normalize_headers(receipt: dict[str, Any]) -> tuple[str, str, str]:
    """Return (header_blob, cookie_blob, content_type) from a receipt dict."""
    raw_headers = receipt.get("response_headers")
    if raw_headers is None:
        raw_headers = receipt.get("headers")

    header_lines: list[str] = []
    cookie_parts: list[str] = []
    header_ctype = ""

    if isinstance(raw_headers, dict):
        for k, v in raw_headers.items():
            key_s = str(k).strip()
            val_s = str(v).strip()
            header_lines.append(f"{key_s}: {val_s}")
            lk = key_s.lower()
            if lk in {"set-cookie", "cookie"}:
                cookie_parts.append(val_s)
            elif lk == "content-type" and not header_ctype:
                header_ctype = val_s
    elif isinstance(raw_headers, str):
        for line in raw_headers.splitlines():
            clean = line.strip()
            if not clean:
                continue
            header_lines.append(clean)
            low = clean.lower()
            if low.startswith(("set-cookie:", "cookie:")):
                cookie_parts.append(clean.split(":", 1)[1].strip())
            elif low.startswith("content-type:") and not header_ctype:
                header_ctype = clean.split(":", 1)[1].strip()

    extra_cookies = receipt.get("cookies")
    if isinstance(extra_cookies, dict):
        cookie_parts.extend(f"{k}={v}" for k, v in extra_cookies.items())
    elif isinstance(extra_cookies, str) and extra_cookies.strip():
        cookie_parts.append(extra_cookies.strip())

    ctype = str(receipt.get("content_type") or header_ctype or "").strip().lower()
    return "\n".join(header_lines), "; ".join(cookie_parts), ctype


def _is_plain_json_app_error(body: str, content_type: str) -> bool:
    """True when response is a structured JSON payload typical of app-level errors."""
    stripped = body.strip()
    if not stripped:
        return False
    looks_json = "json" in content_type or (stripped.startswith("{") and stripped.endswith("}"))
    if not looks_json:
        return False
    try:
        parsed = json.loads(stripped)
    except ValueError:
        return False
    return isinstance(parsed, dict)


def _match_fallback_signatures(
    header_lower: str,
    body_lower: str,
) -> tuple[bool, str | None]:
    """Check explicit WAF/CDN block headers and body signatures offline."""
    for marker, vendor in _EXPLICIT_BLOCK_HEADERS:
        if marker in header_lower:
            return True, vendor

    if "cf-ray" in header_lower and (
        "attention required" in body_lower
        or "cloudflare" in body_lower
        or "error 1020" in body_lower
        or "request blocked" in body_lower
    ):
        return True, "cloudflare"

    for marker, vendor in _VENDOR_BODY_SIGNATURES:
        if marker in body_lower:
            return True, vendor

    if "akamaighost" in header_lower or "x-akamai" in header_lower:
        if any(tok in body_lower for tok in ("access denied", "reference #", "blocked", "akamai")):
            return True, "akamai"

    if "x-cdn: incapsula" in header_lower or "x-iinfo" in header_lower:
        if any(tok in body_lower for tok in ("incapsula", "incident id", "blocked", "unsuccessful")):
            return True, "imperva_incapsula"

    for marker in _GENERIC_WAF_BODY_SIGNATURES:
        if marker in body_lower:
            return True, None

    return False, None


def detect_waf_block(receipt: dict[str, Any]) -> dict[str, Any] | None:
    """Passively classify whether a stored HTTP receipt is an upstream WAF/CDN block.

    Evaluates only statuses in ``{403, 406, 429, 503}`` and returns ``None`` for
    normal application-level authorization/rate JSON errors to avoid false positives.
    """
    if not isinstance(receipt, dict):
        return None

    raw_status = receipt.get("status")
    if isinstance(raw_status, bool) or raw_status is None:
        return None
    try:
        status = int(raw_status)
    except (TypeError, ValueError):
        return None
    if status not in _EVALUATED_STATUSES:
        return None

    header_blob, cookie_blob, content_type = _normalize_headers(receipt)
    body = str(receipt.get("body") or "")
    header_lower = header_blob.lower()
    body_lower = body.lower()

    sig_matched, sig_vendor = _match_fallback_signatures(header_lower, body_lower)
    is_json_app_error = _is_plain_json_app_error(body, content_type)

    classify_http_fn, fingerprint_fn = _load_waf_profiles()
    classified_waf = False
    vendor_hint: str | None = None

    if classify_http_fn is not None:
        try:
            cls_result = classify_http_fn(
                status_code=status,
                headers=header_blob,
                body=body,
                cookies=cookie_blob,
            )
            if isinstance(cls_result, dict):
                if cls_result.get("classification") == "waf_block":
                    classified_waf = True
                hint = cls_result.get("waf_vendor_hint")
                if isinstance(hint, str) and hint and hint != "unknown":
                    vendor_hint = hint
        except Exception:
            classified_waf = False

    if vendor_hint is None and fingerprint_fn is not None:
        try:
            fp_vendor, _score, _matched = fingerprint_fn(
                headers=header_blob,
                cookies=cookie_blob,
                body=body,
                status_code=status,
            )
            if isinstance(fp_vendor, str) and fp_vendor and fp_vendor != "unknown":
                vendor_hint = fp_vendor
        except Exception:
            pass

    # Prevent false positives when an application returns a standard JSON
    # authorization error (e.g. 403 {"error": "forbidden"}) even when hosted
    # behind a CDN reverse proxy whose normal response headers include CF-Ray.
    if is_json_app_error and not sig_matched:
        return None

    if classified_waf or sig_matched:
        vendor = sig_vendor or vendor_hint or "generic"
        return {
            "waf_blocked": True,
            "vendor": vendor,
            "classification": "waf_block",
            "status": status,
        }

    return None
