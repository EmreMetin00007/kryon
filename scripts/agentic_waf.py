def _load_waf_profiles() -> tuple[
    Callable[..., dict[str, Any]] | None,
    Callable[..., tuple[str, int, list[str]]] | None,
]:
    """Lazily import passive classifiers from kryon_core.waf.waf_profiles."""
    global _WAF_PROFILES_LOADED, _CLASSIFY_HTTP, _FINGERPRINT_CHANNELS
    if _WAF_PROFILES_LOADED:
        return _CLASSIFY_HTTP, _FINGERPRINT_CHANNELS
    _WAF_PROFILES_LOADED = True
    try:
        if str(_REPO_ROOT) not in sys.path:
            sys.path.insert(0, str(_REPO_ROOT))
        from kryon_core.waf.waf_profiles import classify_http, fingerprint_channels

        _CLASSIFY_HTTP = classify_http
        _FINGERPRINT_CHANNELS = fingerprint_channels
    except Exception:
        _CLASSIFY_HTTP = None
        _FINGERPRINT_CHANNELS = None
    return _CLASSIFY_HTTP, _FINGERPRINT_CHANNELS


def _normalize_headers(receipt: dict[str, Any]) -> tuple[str, str, str]:
    """Return (header_blob, cookie_blob, content_type) from a receipt dict."""
    raw_headers = receipt.get("response_headers")
    if raw_headers is None:
        raw_headers = receipt.get("headers")

    header_lines: list[str] = []
    cookie_parts: list[str] = []
    header_ctype = ""

    if isinstance(raw_headers, dict):
        for k, v in raw_headers.items():
            key_s = str(k).strip()
            val_s = str(v).strip()
            header_lines.append(f"{key_s}: {val_s}")
            lk = key_s.lower()
            if lk in {"set-cookie", "cookie"}:
                cookie_parts.append(val_s)
            elif lk == "content-type" and not header_ctype:
                header_ctype = val_s
    elif isinstance(raw_headers, str):
        for line in raw_headers.splitlines():
            clean = line.strip()
            if not clean:
                continue
            header_lines.append(clean)
            low = clean.lower()
            if low.startswith(("set-cookie:", "cookie:")):
                cookie_parts.append(clean.split(":", 1)[1].strip())
            elif low.startswith("content-type:") and not header_ctype:
                header_ctype = clean.split(":", 1)[1].strip()

    extra_cookies = receipt.get("cookies")
    if isinstance(extra_cookies, dict):
        cookie_parts.extend(f"{k}={v}" for k, v in extra_cookies.items())
    elif isinstance(extra_cookies, str) and extra_cookies.strip():
        cookie_parts.append(extra_cookies.strip())

    ctype = str(receipt.get("content_type") or header_ctype or "").strip().lower()
    return "\n".join(header_lines), "; ".join(cookie_parts), ctype


def _is_plain_json_app_error(body: str, content_type: str) -> bool:
    """True when response is a structured JSON payload typical of app-level errors."""
    stripped = body.strip()
    if not stripped:
        return False
    looks_json = "json" in content_type or (stripped.startswith("{") and stripped.endswith("}"))
    if not looks_json:
        return False
    try:
        parsed = json.loads(stripped)
    except ValueError:
        return False
    return isinstance(parsed, dict)


def _match_fallback_signatures(
    header_lower: str,
    body_lower: str,
) -> tuple[bool, str | None]:
    """Check explicit WAF/CDN block headers and body signatures offline."""
    for marker, vendor in _EXPLICIT_BLOCK_HEADERS:
        if marker in header_lower:
            return True, vendor

    if "cf-ray" in header_lower and (
        "attention required" in body_lower
        or "cloudflare" in body_lower
        or "error 1020" in body_lower
        or "request blocked" in body_lower
    ):
        return True, "cloudflare"

    for marker, vendor in _VENDOR_BODY_SIGNATURES:
        if marker in body_lower:
            return True, vendor

    if "akamaighost" in header_lower or "x-akamai" in header_lower:
        if any(tok in body_lower for tok in ("access denied", "reference #", "blocked", "akamai")):
            return True, "akamai"

    if "x-cdn: incapsula" in header_lower or "x-iinfo" in header_lower:
        if any(tok in body_lower for tok in ("incapsula", "incident id", "blocked", "unsuccessful")):
            return True, "imperva_incapsula"

    for marker in _GENERIC_WAF_BODY_SIGNATURES:
        if marker in body_lower:
            return True, None

    return False, None


def _request_contains_attack_probe(receipt: dict[str, Any]) -> bool:
    """True when the request URL/query/body carries an explicit active-attack test pattern."""
    raw_url = str(receipt.get("url") or receipt.get("path") or "")
    raw_body = str(receipt.get("request_body") or "")
    parsed = urlsplit(raw_url)
    path_and_query = f"{parsed.path}?{parsed.query}" if parsed.query else parsed.path
    decoded_url = unquote_plus(path_and_query)
    decoded_body = unquote_plus(raw_body[:4096]) if raw_body else ""
    samples = (path_and_query, decoded_url, raw_body[:4096], decoded_body)
    return any(pat.search(sample) for sample in samples if sample for pat in _ATTACK_PROBE_PATTERNS)


def _is_behavioral_edge_block(
    *,
    status: int,
    receipt: dict[str, Any],
    header_lower: str,
    body_lower: str,
    content_type: str,
    is_json_app_error: bool,
) -> bool:
    """Detect generic edge/ModSecurity 403/406 HTML blocks triggered by active-attack payloads."""
    if status not in {403, 406} or is_json_app_error:
        return False
    if len(body_lower) > 32768:
        return False
    url_path = (urlsplit(str(receipt.get("url") or receipt.get("path") or "")).path or "").lower()
    if any(tok in url_path for tok in _AUTH_OR_CSRF_PATH_TOKENS):
        return False
    is_html_or_text = (
        not content_type
        or "html" in content_type
        or "text/plain" in content_type
        or "<html" in body_lower[:512]
    )
    if not is_html_or_text:
        return False
    has_block_text = any(
        marker in body_lower
        for marker in ("403 forbidden", "406 not acceptable", "<title>403", "<title>406", "<h1>403", "<h1>406", "access denied", "request blocked", "forbidden")
    )
    if not has_block_text:
        return False
    has_proxy_or_default_page = (
        any(srv in header_lower or srv in body_lower for srv in _PROXY_SERVER_HINTS)
        or "<center><h1>403 forbidden</h1></center>" in body_lower
        or "<title>403 forbidden</title>" in body_lower
        or "<title>406 not acceptable</title>" in body_lower
    )
    if not has_proxy_or_default_page:
        return False
    return _request_contains_attack_probe(receipt)


def detect_waf_block(receipt: dict[str, Any]) -> dict[str, Any] | None:
    """Passively classify whether a stored HTTP receipt is an upstream WAF/CDN block.

    Evaluates only statuses in ``{403, 406, 429, 503}`` and returns ``None`` for
    normal application-level authorization/rate JSON errors to avoid false positives.
    """
    if not isinstance(receipt, dict):
        return None

    raw_status = receipt.get("status")
    if isinstance(raw_status, bool) or raw_status is None:
        return None
    try:
        status = int(raw_status)
    except (TypeError, ValueError):
        return None
    if status not in _EVALUATED_STATUSES:
        return None

    header_blob, cookie_blob, content_type = _normalize_headers(receipt)
    body = str(receipt.get("body") or "")
    header_lower = header_blob.lower()
    body_lower = body.lower()

    sig_matched, sig_vendor = _match_fallback_signatures(header_lower, body_lower)
    is_json_app_error = _is_plain_json_app_error(body, content_type)

    classify_http_fn, fingerprint_fn = _load_waf_profiles()
    classified_waf = False
    vendor_hint: str | None = None

    if classify_http_fn is not None:
        try:
            cls_result = classify_http_fn(
                status_code=status,
                headers=header_blob,
                body=body,
                cookies=cookie_blob,
            )
            if isinstance(cls_result, dict):
                if cls_result.get("classification") == "waf_block":
                    classified_waf = True
                hint = cls_result.get("waf_vendor_hint")
                if isinstance(hint, str) and hint and hint != "unknown":
                    vendor_hint = hint
        except Exception:
            classified_waf = False

    if vendor_hint is None and fingerprint_fn is not None:
        try:
            fp_vendor, _score, _matched = fingerprint_fn(
                headers=header_blob,
                cookies=cookie_blob,
                body=body,
                status_code=status,
            )
            if isinstance(fp_vendor, str) and fp_vendor and fp_vendor != "unknown":
                vendor_hint = fp_vendor
        except Exception:
            pass

    # Prevent false positives when an application returns a standard JSON
    # authorization error (e.g. 403 {"error": "forbidden"}) even when hosted
    # behind a CDN reverse proxy whose normal response headers include CF-Ray.
    if is_json_app_error and not sig_matched:
        return None

    if classified_waf or sig_matched:
        vendor = sig_vendor or vendor_hint or "generic"
        return {
            "waf_blocked": True,
            "vendor": vendor,
            "classification": "waf_block",
            "status": status,
        }

    if _is_behavioral_edge_block(
        status=status,
        receipt=receipt,
        header_lower=header_lower,
        body_lower=body_lower,
        content_type=content_type,
        is_json_app_error=is_json_app_error,
    ):
        return {
            "waf_blocked": True,
            "vendor": vendor_hint or "edge_waf",
            "classification": "waf_block",
            "status": status,
        }

    return None


_WAF_UUID_RE = re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$", re.I)
_WAF_HEX_RE = re.compile(r"^[0-9a-f]{16,}$", re.I)


def _normalize_waf_path_template(url_or_path: str) -> str:
    """Normalize a receipt path or URL into a compact `{id}` route template."""
    raw = str(url_or_path or "").strip()
    if not raw:
        return "/"
    parsed = urlsplit(raw)
    path = (parsed.path or "/").strip()
    if len(path) > 1:
        path = path.rstrip("/")
    if not path or path == "/":
        return "/"
    segs: list[str] = []
    for seg in path.split("/"):
        if not seg:
            continue
        low = seg.lower()
        if low.isdigit() or _WAF_UUID_RE.fullmatch(low) or _WAF_HEX_RE.fullmatch(low):
            segs.append("{id}")
        else:
            segs.append(low)
    return "/" + "/".join(segs)


def build_waf_pivot_guidance(
    vendor: str,
    blocked_paths: Sequence[str] | Iterable[str] = (),
    total_blocks: int = 0,
) -> str:
    """Build a concise, actionable pivot directive when upstream WAF blocks accumulate."""
    try:
        count = int(total_blocks)
    except (TypeError, ValueError):
        count = 0
    if count < 2:
        return ""

    clean_vendor = str(vendor or "").strip().lower() or "generic"
    unique_paths: list[str] = []
    seen_paths: set[str] = set()
    for raw_path in blocked_paths or ():
        norm = _normalize_waf_path_template(str(raw_path or ""))
        if norm not in seen_paths:
            seen_paths.add(norm)
            unique_paths.append(norm)
        if len(unique_paths) >= 5:
            break

    paths_label = ", ".join(unique_paths) if unique_paths else "/"
    return (
        f"WAF pivot advisory ({clean_vendor}, {count} blocks on {paths_label}): "
        "Stop repeating signature-blocked XSS/SQLi probes against this WAF edge. "
        "Immediately pivot to WAF-blind vulnerability classes: "
        "(1) BOLA/IDOR cross-actor replay via replay_as, "
        "(2) BFLA / missing function-level authorization, "
        "(3) mass assignment & JSON business-logic / type confusion, "
        "(4) race conditions / TOCTOU via concurrent_check, "
        "(5) CORS / HTTP header anomalies, and "
        "(6) client-side JS/config secret & route inspection."
    )


class WAFPivotTracker:
    """Thread-safe tracker of upstream WAF blocks per `(vendor, path_template)` and overall."""

    def __init__(self, *, threshold: int = 2) -> None:
        if isinstance(threshold, bool) or int(threshold) < 1:
            raise ValueError("threshold must be a positive integer")
        self.threshold = int(threshold)
        self._lock = threading.Lock()
        self._total_blocks: int = 0
        self._by_vendor: dict[str, int] = {}
        self._by_pair: dict[tuple[str, str], int] = {}
        self._paths_by_vendor: dict[str, list[str]] = {}
        self._all_paths: list[str] = []

    @property
    def total_blocks(self) -> int:
        with self._lock:
            return self._total_blocks

    def _record_block_locked(self, vendor: str, path_template: str) -> dict[str, Any]:
        clean_vendor = str(vendor or "").strip().lower() or "generic"
        norm_path = _normalize_waf_path_template(path_template)
        self._total_blocks += 1
        self._by_vendor[clean_vendor] = self._by_vendor.get(clean_vendor, 0) + 1
        pair = (clean_vendor, norm_path)
        self._by_pair[pair] = self._by_pair.get(pair, 0) + 1
        if norm_path not in self._all_paths:
            self._all_paths.append(norm_path)
        vendor_paths = self._paths_by_vendor.setdefault(clean_vendor, [])
        if norm_path not in vendor_paths:
            vendor_paths.append(norm_path)
        pivot = self._should_pivot_locked()
        return {
            "waf_blocked": True,
            "vendor": clean_vendor,
            "path_template": norm_path,
            "total_blocks": self._total_blocks,
            "vendor_blocks": self._by_vendor[clean_vendor],
            "route_blocks": self._by_pair[pair],
            "should_pivot": pivot,
        }

    def _should_pivot_locked(
        self,
        *,
        vendor: str | None = None,
        path_template: str | None = None,
    ) -> bool:
        if vendor is not None and path_template is not None:
            clean_vendor = str(vendor).strip().lower() or "generic"
            norm_path = _normalize_waf_path_template(path_template)
            return self._by_pair.get((clean_vendor, norm_path), 0) >= self.threshold
        if vendor is not None:
            clean_vendor = str(vendor).strip().lower() or "generic"
            return self._by_vendor.get(clean_vendor, 0) >= self.threshold
        if path_template is not None:
            norm_path = _normalize_waf_path_template(path_template)
            route_total = sum(
                count for (_v, p), count in self._by_pair.items() if p == norm_path
            )
            return route_total >= self.threshold
        return (
            self._total_blocks >= self.threshold
            or any(count >= self.threshold for count in self._by_vendor.values())
            or any(count >= self.threshold for count in self._by_pair.values())
        )

    def record_block(self, vendor: str = "generic", path_template: str = "/") -> dict[str, Any]:
        """Explicitly record a confirmed WAF block event for `(vendor, path_template)`."""
        with self._lock:
            return self._record_block_locked(vendor, path_template)

    def record_receipt(
        self,
        receipt: dict[str, Any],
        *,
        path_template: str = "",
    ) -> dict[str, Any] | None:
        """Inspect a receipt via `detect_waf_block` and track any upstream WAF block."""
        waf_info = detect_waf_block(receipt)
        if waf_info is None:
            return None
        raw_path = path_template or str(receipt.get("path") or receipt.get("url") or "/")
        with self._lock:
            recorded = self._record_block_locked(str(waf_info.get("vendor") or "generic"), raw_path)
            return {
                **waf_info,
                "path_template": recorded["path_template"],
                "total_blocks": recorded["total_blocks"],
                "vendor_blocks": recorded["vendor_blocks"],
                "route_blocks": recorded["route_blocks"],
                "should_pivot": recorded["should_pivot"],
            }

    def record(
        self,
        receipt_or_vendor: dict[str, Any] | str,
        *,
        path_template: str = "",
    ) -> dict[str, Any] | None:
        """Record either a receipt dict (via `detect_waf_block`) or an explicit vendor name."""
        if isinstance(receipt_or_vendor, dict):
            return self.record_receipt(receipt_or_vendor, path_template=path_template)
        return self.record_block(str(receipt_or_vendor or "generic"), path_template or "/")

    def should_pivot(
        self,
        vendor: str | None = None,
        path_template: str | None = None,
    ) -> bool:
        """Return True once recorded WAF blocks reach the pivot threshold."""
        with self._lock:
            return self._should_pivot_locked(vendor=vendor, path_template=path_template)

    def guidance(self, *, vendor: str | None = None) -> str:
        """Return a concise pivot directive once `should_pivot()` is True, else empty string."""
        with self._lock:
            if not self._should_pivot_locked(vendor=vendor):
                return ""
            if vendor is not None:
                eff_vendor = str(vendor).strip().lower() or "generic"
                paths = list(self._paths_by_vendor.get(eff_vendor) or self._all_paths)
                count = self._by_vendor.get(eff_vendor, self._total_blocks)
            elif self._by_vendor:
                eff_vendor = max(
                    sorted(self._by_vendor),
                    key=lambda v: self._by_vendor[v],
                )
                paths = list(self._all_paths)
                count = self._total_blocks
            else:
                eff_vendor = "generic"
                paths = list(self._all_paths)
                count = self._total_blocks
            return build_waf_pivot_guidance(eff_vendor, paths, count)

    def summary(self) -> dict[str, Any]:
        """Return a thread-safe snapshot of tracked WAF blocks and pivot readiness."""
        with self._lock:
            return {
                "total_blocks": self._total_blocks,
                "should_pivot": self._should_pivot_locked(),
                "vendors": dict(sorted(self._by_vendor.items())),
                "blocked_paths": list(self._all_paths),
                "route_counts": {
                    f"{v}:{p}": count for (v, p), count in sorted(self._by_pair.items())
                },
            }
